package com.animeow.app.data.backup

/** Local failure-injection boundaries; never persisted in a backup or exposed as a product option. */
internal enum class NativeRestoreStage {
    COVERS_COPIED, BRANDING_BACKED_UP, BRANDING_CLEARED, BRANDING_COPIED,
    DATABASE_REPLACED, PLAYBACK_HISTORY_WRITTEN, APPEARANCE_WRITTEN, ANALYSIS_WRITTEN, DISCOVERY_WRITTEN,
    CALENDAR_WRITTEN, MAINTENANCE_WRITTEN, BRANDING_WRITTEN, TRACKER_WRITTEN,
    FILTERS_WRITTEN, EDITOR_WRITTEN, CLOUD_WRITTEN, PROFILES_WRITTEN,
    DATABASE_COMMITTED, DERIVED_TASKS_REBUILT, BEFORE_BRANDING_ROLLBACK,
    BEFORE_REMINDER_REBUILD, BEFORE_CLOUD_REBUILD, BEFORE_STAGING_CLEANUP,
    COPYING_COVERS, COPYING_BRANDING_BACKUP, COPYING_BRANDING, COPYING_BRANDING_ROLLBACK,
}

class NativeRestoreRollbackException(cause: Throwable) : IllegalStateException(
    "恢复未完成，部分修改未能撤回，请暂停恢复并核对本机资料", cause,
)
